/** Map app locale to an Intl/BCP-47 locale tag for date/number formatting. */
export function localeToIntl(locale: AppLocale): string {
  if (locale === "ca") return "ca-ES";
  if (locale === "en") return "en-GB";
  return "es-ES";
}
