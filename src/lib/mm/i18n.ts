const DICTS: Record<MMLang, Dict> = { es, ca, en, fr };
export type MMKey = keyof Dict;

export function mmT(lang: string | null | undefined, key: MMKey, vars: Record<string, string | number> = {}) {
  const d = DICTS[(lang as MMLang) ?? "es"] ?? es;
  return (d[key] ?? es[key]).replace(/\{(\w+)\}/g, (_, k) => String(vars[k] ?? ""));
}
export const mmLocale = (lang: string | null | undefined) => ({ es: "es-ES", ca: "ca-ES", en: "en-GB", fr: "fr-FR" })[(lang as MMLang) ?? "es"] ?? "es-ES";
